package com.littlesauce.usbnas;

import android.graphics.Bitmap;
import android.graphics.Color;

import com.google.zxing.BarcodeFormat;
import com.google.zxing.EncodeHintType;
import com.google.zxing.qrcode.QRCodeWriter;
import com.google.zxing.qrcode.decoder.ErrorCorrectionLevel;

import java.util.EnumMap;
import java.util.Map;

/** ZXing 薄封装：把短 URL 变成 Bitmap */
public final class QrUtil {

    private QrUtil() {}

    public static Bitmap make(String text, int pixelSize) {
        return make(text, pixelSize, Color.BLACK, Color.WHITE);
    }

    public static Bitmap make(String text, int pixelSize, int fg, int bg) {
        try {
            Map<EncodeHintType, Object> hints = new EnumMap<>(EncodeHintType.class);
            hints.put(EncodeHintType.CHARACTER_SET, "UTF-8");
            hints.put(EncodeHintType.ERROR_CORRECTION, ErrorCorrectionLevel.M);
            hints.put(EncodeHintType.MARGIN, 1);

            var matrix = new QRCodeWriter().encode(text, BarcodeFormat.QR_CODE,
                    pixelSize, pixelSize, hints);
            int w = matrix.getWidth();
            int h = matrix.getHeight();
            int[] pixels = new int[w * h];
            for (int y = 0; y < h; y++) {
                int off = y * w;
                for (int x = 0; x < w; x++) {
                    pixels[off + x] = matrix.get(x, y) ? fg : bg;
                }
            }
            Bitmap bmp = Bitmap.createBitmap(w, h, Bitmap.Config.ARGB_8888);
            bmp.setPixels(pixels, 0, w, 0, 0, w, h);
            return bmp;
        } catch (Throwable e) {
            return null;
        }
    }
}
